        //        button.setActionCommand("Insets");
        //        button.addActionListener(this);
        //
        //        this.insetsTextField = new InsetsTextField(this.plotInsets);
        //        this.insetsTextField.setEnabled(false);
        //        interior.add(this.insetsTextField);
        //        interior.add(button);
